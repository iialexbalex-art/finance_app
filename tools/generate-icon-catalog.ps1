$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot
$items=Get-Content "$root/assets/icons/catalog.json" -Raw -Encoding UTF8 | ConvertFrom-Json
$lines=@("// Generated by tools/generate-icon-catalog.ps1. Asset provenance: assets/icons/catalog.json.", "class WalletIconChoice {", "  const WalletIconChoice(this.id, this.label, this.group, this.asset, this.synonyms);", "  final String id, label, group, asset, synonyms;", "}", "const categoryIconCatalog = <WalletIconChoice>[")
$i=0
foreach($item in $items){
  if($i -eq 80){$lines+='];'; $lines+='const financialIconCatalog = <WalletIconChoice>['}
  $lines+="  WalletIconChoice('$($item.id)', '$($item.label)', '$($item.group)', '$($item.asset)', '$($item.synonyms)'),"
  $i++
}
$lines+='];'
[IO.File]::WriteAllText("$root/lib/icon_catalog.dart",($lines -join "`n"),[Text.UTF8Encoding]::new($false))
