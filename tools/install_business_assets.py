"""Generate local assets/catalog from the supplied authoritative package.

Copies PNG bytes unchanged; never connects to Supabase or installs database data.
"""
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / 'design/business-expenses-pack'


def dart(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')


def main():
    catalog = json.loads((PACK / 'catalog.json').read_text(encoding='utf-8-sig'))
    manifest = json.loads((PACK / 'asset-manifest.json').read_text(encoding='utf-8-sig'))
    categories = catalog['categories']
    assert len(categories) == 62
    assert sum(c['parent_key'] is None for c in categories) == 11
    assert len({c['key'] for c in categories}) == 62
    assert len({c['icon_id'] for c in categories}) == 62
    by_key = {c['key']: c for c in categories}
    destination = ROOT / 'assets/business_expenses'
    destination.mkdir(exist_ok=True)
    for entry in manifest['images']:
        source = PACK / entry['file']
        image = source.read_bytes()
        assert hashlib.sha256(image).hexdigest() == entry['sha256'], source
        assert image[:8] == b'\x89PNG\r\n\x1a\n'
        assert entry['alpha_range'] == [0, 255]
        assert by_key[entry['category_key']]['asset_file'] == entry['file']
        shutil.copyfile(source, destination / source.name)
    lines = ["// Generated by tools/install_business_assets.py from catalog.json.",
             "import 'icon_catalog.dart';", "import 'category.dart';", '',
             'const businessExpenseIconCatalog = <WalletIconChoice>[']
    for c in categories:
        group = by_key[c['parent_key']]['name'] if c['parent_key'] else c['name']
        lines.append('  WalletIconChoice(%s, %s, %s, %s, %s),' % tuple(map(dart, [
            c['icon_id'], c['name'], 'Бизнес · ' + group,
            'assets/business_expenses/' + Path(c['asset_file']).name,
            ' '.join(c['aliases'])])))
    lines += ['];', '', '// QA fixtures only; the application never seeds categories on launch.',
              'List<FinanceCategory> businessExpenseFixtures(String spaceId) => [']
    for c in categories:
        lines.append('  FinanceCategory(id: %s, spaceId: spaceId, kind: CategoryKind.expense, name: %s, parentId: %s, iconId: %s, sortOrder: %d),' % (
            dart(c['key']), dart(c['name']), dart(c['parent_key']) if c['parent_key'] else 'null',
            dart(c['icon_id']), c['sort_order']))
    lines += ['];', '']
    (ROOT / 'lib/business_expense_catalog.dart').write_text('\n'.join(lines), encoding='utf-8')
    # Trim prompts from runtime registry, keeping every semantic catalog field.
    (destination / 'catalog.json').write_text(json.dumps({
        **{k: v for k, v in catalog.items() if k != 'categories'},
        'categories': [{k: v for k, v in c.items() if k != 'prompt'} for c in categories],
    }, ensure_ascii=False, indent=2), encoding='utf-8')
    def sql(value):
        return 'null' if value is None else "'" + str(value).replace("'", "''") + "'"
    values = []
    for c in categories:
        values.append('  (' + ','.join([
            sql(c['key']), sql(c['name']), sql(c['parent_key']), sql(c['path']),
            str(c['sort_order']), sql(c['icon_id']), sql(json.dumps(c['aliases'], ensure_ascii=False)) + '::jsonb',
        ]) + ')')
    template = (ROOT / 'supabase/business_expenses_migration.template.sql').read_text(encoding='utf-8')
    migration = template.replace('__CATALOG_VALUES__', ',\n'.join(values))
    (ROOT / 'supabase/migrations/202610060015_business_expenses.sql').write_text(migration, encoding='utf-8')
    print('Verified and copied 62 original PNGs; generated stable key catalog.')


if __name__ == '__main__':
    main()
