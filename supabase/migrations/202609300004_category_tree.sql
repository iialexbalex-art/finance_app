lock table public.categories in access exclusive mode;

-- Частная служебная строка сериализует ВСЕ записи дерева до конца транзакции.
-- Реальный UPDATE (а не advisory lock) также обнаруживает устаревший snapshot
-- REPEATABLE READ/SERIALIZABLE: PostgreSQL отклоняет проигравшую транзакцию.
create table finance_private.category_tree_guard (
  singleton boolean primary key default true check (singleton),
  flip boolean not null default false
);
insert into finance_private.category_tree_guard(singleton) values (true);
revoke all on finance_private.category_tree_guard from public, anon, authenticated;

create function finance_private.lock_category_tree()
returns trigger language plpgsql volatile security definer set search_path = ''
as $function$
begin
  update finance_private.category_tree_guard set flip = not flip where singleton;
  if not found then raise exception 'Missing category tree guard'; end if;
  return null;
end
$function$;
revoke all on function finance_private.lock_category_tree() from public, anon, authenticated;
create trigger categories_serialize_writes
before insert or update or delete on public.categories
for each statement execute function finance_private.lock_category_tree();

-- Убираем только старый FK, требующий корневого родителя.
-- Имя находим по столбцу, не полагаясь на усечение autogenerated имени.
do $constraints$
declare c record; removed integer := 0;
begin
  for c in select conname from pg_constraint
    where conrelid = 'public.categories'::regclass and contype = 'f'
      and (select attnum from pg_attribute where attrelid = 'public.categories'::regclass
           and attname = 'parent_must_be_root') = any(conkey)
  loop
    execute format('alter table public.categories drop constraint %I', c.conname);
    removed := removed + 1;
  end loop;
  if removed <> 1 then raise exception 'Unexpected categories schema'; end if;
end
$constraints$;
alter table public.categories drop column parent_must_be_root;
