drop trigger categories_check_parent on public.categories;
-- Проверяет всю цепочку НОВОГО родителя, включая архив всех предков.
-- AFTER ROW видит окончательный результат statement, включая multi-row UPDATE.
create or replace function finance_private.check_category_parent()
returns trigger language plpgsql volatile security invoker set search_path = ''
as $function$
declare p public.categories%rowtype; next_id uuid; visited uuid[]; depth integer := 1;
begin
  if tg_op = 'UPDATE' then
    if new.parent_id is not distinct from old.parent_id then return new; end if;
  end if;
  next_id := new.parent_id;
  visited := array[new.id];
  while next_id is not null loop
    if next_id = any(visited) or depth >= 3 then
      raise exception using errcode = '23514', message = 'Category cycle or depth exceeds three';
    end if;
    select * into p from public.categories where id = next_id;
    if not found or p.space_id <> new.space_id or p.kind <> new.kind or p.is_archived then
      raise exception using errcode = '23514', message = 'Invalid or archived category ancestor';
    end if;
    visited := array_append(visited, next_id);
    next_id := p.parent_id;
    depth := depth + 1;
  end loop;
  return new;
end
$function$;
revoke all on function finance_private.check_category_parent() from public, anon, authenticated;
create trigger categories_check_parent
after insert or update of parent_id on public.categories
for each row execute function finance_private.check_category_parent();

-- Проверяем всех потомков, а не только глубину переносимой записи.
-- VOLATILE: свежие snapshots запросов после ожидания guard при READ COMMITTED.
create function finance_private.validate_category_tree()
returns trigger language plpgsql volatile security definer set search_path = ''
as $function$
begin
  if exists (
    with recursive ancestry as (
      select id, parent_id, array[id] as visited, 1 as depth, false as cycle
      from public.categories
      union all
      select a.id, p.parent_id, a.visited || p.id, a.depth + 1, p.id = any(a.visited)
      from ancestry a join public.categories p on p.id = a.parent_id
      where a.depth < 4 and not a.cycle
    ) select 1 from ancestry where depth > 3 or cycle
  ) then
    raise exception using errcode = '23514', message = 'Category cycle or subtree depth exceeds three';
  end if;
  return null;
end
$function$;
revoke all on function finance_private.validate_category_tree() from public, anon, authenticated;
create trigger categories_validate_tree
after insert or update on public.categories
for each statement execute function finance_private.validate_category_tree();

